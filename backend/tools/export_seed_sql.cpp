// ============================================================================
// NEXA :: export_seed_sql — runs the C++ demo seeder against in-memory
// repositories and prints equivalent SQL INSERT statements, so the MySQL
// seed file is generated from the single source of truth (DemoSeeder.cpp).
//
//   export_seed_sql > ../database/seed/seed_demo.sql
//   export_seed_sql --map-data ../map_data       (locations + roads as CSV)
//
// Note: the backend also seeds automatically on first start ("auto_seed"),
// which gives timestamps relative to the moment you start it. This file has
// timestamps fixed at the time it was generated.
// ============================================================================
#include <cstdio>
#include <string>
#include "repositories/InMemoryRepositories.hpp"
#include "services/NexaCore.hpp"

using namespace nexa;

namespace {
std::string q(const std::string& s) {
    std::string o = "'";
    for (char c : s) { if (c == '\'') o += "''"; else if (c == '\\') o += "\\\\"; else o += c; }
    return o + "'";
}
std::string t(long epoch) { return epoch > 0 ? "FROM_UNIXTIME(" + std::to_string(epoch) + ")" : "NULL"; }
std::string d(double v) { char b[40]; std::snprintf(b, sizeof b, "%.6f", v); return b; }
std::string nz(long v) { return v ? std::to_string(v) : "NULL"; }
}

int main(int argc, char* argv[]) {
    util::Logger::instance().setEcho(false);
    svc::EngineConfig cfg;
    svc::NullSink sink;
    auto bundle = repo::makeInMemoryBundle();
    svc::NexaCore core(cfg, bundle, sink);
    core.seedDemoData();

    // `export_seed_sql --map-data <dir>` writes the road network as CSV instead
    if (argc == 3 && std::string(argv[1]) == "--map-data") {
        std::string dir = argv[2];
        if (FILE* f = std::fopen((dir + "/locations/delhi_ncr_locations.csv").c_str(), "w")) {
            std::fprintf(f, "id,name,kind,latitude,longitude\n");
            for (const auto& l : bundle.locations->findLocations()) std::fprintf(f, "%ld,\"%s\",%s,%s,%s\n", l.id, l.name.c_str(), l.kind.c_str(), d(l.lat).c_str(), d(l.lon).c_str());
            std::fclose(f);
        }
        if (FILE* f = std::fopen((dir + "/road_networks/delhi_ncr_roads.csv").c_str(), "w")) {
            std::fprintf(f, "id,from_location_id,to_location_id,name,distance_km,travel_minutes_estimated,penalty,blocked\n");
            for (const auto& r : bundle.locations->findRoads())
                std::fprintf(f, "%ld,%ld,%ld,\"%s\",%s,%s,%s,%d\n", r.id, r.fromId, r.toId, r.name.c_str(), d(r.distanceKm).c_str(), d(r.travelMinutes).c_str(), d(r.penalty).c_str(), r.blocked ? 1 : 0);
            std::fclose(f);
        }
        std::printf("map data written to %s\n", dir.c_str());
        return 0;
    }

    std::printf("-- NEXA demo dataset — SIMULATED DATA (generated by tools/export_seed_sql)\n");
    std::printf("-- Apply after schema.sql:  mysql -u root -p nexa < database/seed/seed_demo.sql\n");
    std::printf("USE nexa;\nSET FOREIGN_KEY_CHECKS = 0;\nSTART TRANSACTION;\n\n");

    for (const auto& c : bundle.categories->findAll())
        std::printf("INSERT INTO incident_categories(id,parent_id,name,code,time_sensitivity,default_capabilities) VALUES(%d,%s,%s,%s,%s,%s);\n",
                    c.id, c.parentId ? std::to_string(c.parentId).c_str() : "NULL", q(c.name).c_str(), q(c.code).c_str(), d(c.timeSensitivity).c_str(), q(c.defaultCapabilities).c_str());
    for (const auto& r : bundle.resources->findTypes())
        std::printf("INSERT INTO resource_types(id,name,category,default_capabilities) VALUES(%d,%s,%s,%s);\n", r.id, q(r.name).c_str(), q(r.category).c_str(), q(r.defaultCapabilities).c_str());
    std::printf("\n");
    for (const auto& l : bundle.locations->findLocations())
        std::printf("INSERT INTO locations(id,name,kind,latitude,longitude) VALUES(%ld,%s,%s,%s,%s);\n", l.id, q(l.name).c_str(), q(l.kind).c_str(), d(l.lat).c_str(), d(l.lon).c_str());
    for (const auto& r : bundle.locations->findRoads())
        std::printf("INSERT INTO roads(id,from_location_id,to_location_id,name,distance_km,travel_minutes,penalty,blocked) VALUES(%ld,%ld,%ld,%s,%s,%s,%s,%d);\n",
                    r.id, r.fromId, r.toId, q(r.name).c_str(), d(r.distanceKm).c_str(), d(r.travelMinutes).c_str(), d(r.penalty).c_str(), r.blocked ? 1 : 0);
    std::printf("\n");
    for (const auto& h : bundle.hospitals->findAll())
        std::printf("INSERT INTO hospitals(id,name,category,latitude,longitude,total_beds,available_beds,icu_beds,icu_available,capabilities,contact,address,updated_at) VALUES(%ld,%s,%s,%s,%s,%d,%d,%d,%d,%s,%s,%s,%s);\n",
                    h.id, q(h.name).c_str(), q(h.category).c_str(), d(h.lat).c_str(), d(h.lon).c_str(), h.totalBeds, h.availableBeds, h.icuBeds, h.icuAvailable,
                    q(h.capabilities).c_str(), q(h.contact).c_str(), q(h.address).c_str(), t(h.updatedAt).c_str());
    std::printf("\n");
    for (const auto& r : bundle.resources->findAll()) {
        std::printf("INSERT IGNORE INTO response_teams(name) VALUES(%s);\n", q(r.organization).c_str());
        std::printf("INSERT INTO resources(id,code,name,type_id,team_id,capacity,available,status,latitude,longitude,capabilities,updated_at) VALUES(%ld,%s,%s,%d,(SELECT id FROM response_teams WHERE name=%s),%d,%d,%s,%s,%s,%s,%s);\n",
                    r.id, q(r.code).c_str(), q(r.name).c_str(), r.typeId, q(r.organization).c_str(), r.capacity, r.available, q(model::toString(r.status)).c_str(),
                    d(r.lat).c_str(), d(r.lon).c_str(), q(r.capabilities).c_str(), t(r.updatedAt).c_str());
    }
    std::printf("\n");
    for (const auto& i : bundle.incidents->findAll())
        std::printf("INSERT INTO incidents(id,code,title,description,category_id,severity,latitude,longitude,location_name,status,affected_people,required_capabilities,required_units,reported_by,reporter_contact,created_at,updated_at,resolved_at,simulated,scenario_id) "
                    "VALUES(%ld,%s,%s,%s,%d,%d,%s,%s,%s,%s,%ld,%s,%d,%s,%s,%s,%s,%s,%d,NULL);\n",
                    i.id, q(i.code).c_str(), q(i.title).c_str(), q(i.description).c_str(), i.categoryId, i.severity, d(i.lat).c_str(), d(i.lon).c_str(), q(i.locationName).c_str(),
                    q(model::toString(i.status)).c_str(), i.affectedPeople, q(i.requiredCapabilities).c_str(), i.requiredUnits, q(i.reportedBy).c_str(), q(i.reporterContact).c_str(),
                    t(i.createdAt).c_str(), t(i.updatedAt).c_str(), t(i.resolvedAt).c_str(), i.simulated ? 1 : 0);
    for (const auto& e : bundle.events->findAll())
        std::printf("INSERT INTO incident_events(id,incident_id,event_type,message,actor,created_at) VALUES(%ld,%ld,%s,%s,%s,%s);\n",
                    e.id, e.incidentId, q(e.type).c_str(), q(e.message).c_str(), q(e.actor).c_str(), t(e.createdAt).c_str());
    std::printf("\n");
    for (const auto& r : bundle.requests->findAll())
        std::printf("INSERT INTO emergency_requests(id,incident_id,assistance_type,description,urgency,people_affected,status,urgency_score,requested_by,created_at,processed_at,deployment_id) VALUES(%ld,%ld,%s,%s,%d,%ld,%s,%s,%s,%s,%s,%s);\n",
                    r.id, r.incidentId, q(r.assistanceType).c_str(), q(r.description).c_str(), r.urgency, r.peopleAffected, q(model::toString(r.status)).c_str(),
                    d(r.urgencyScore).c_str(), q(r.requestedBy).c_str(), t(r.createdAt).c_str(), t(r.processedAt).c_str(), nz(r.deploymentId).c_str());
    for (const auto& dp : bundle.deployments->findAll()) {
        std::printf("INSERT INTO deployments(id,incident_id,request_id,status,created_by,notes,created_at,completed_at) VALUES(%ld,%ld,%s,%s,%s,%s,%s,%s);\n",
                    dp.id, dp.incidentId, nz(dp.requestId).c_str(), q(model::toString(dp.status)).c_str(), q(dp.createdBy).c_str(), q(dp.notes).c_str(), t(dp.createdAt).c_str(), t(dp.completedAt).c_str());
        for (const auto& x : dp.resources)
            std::printf("INSERT INTO deployment_resources(deployment_id,resource_id,units,suitability,route_km,eta_minutes,reason,released,released_at) VALUES(%ld,%ld,%d,%s,%s,%s,%s,%d,%s);\n",
                        dp.id, x.resourceId, x.units, d(x.suitability).c_str(), d(x.routeKm).c_str(), d(x.etaMinutes).c_str(), q(x.reason).c_str(), x.released ? 1 : 0, t(x.releasedAt).c_str());
    }
    for (const auto& h : bundle.resources->findHistory())
        std::printf("INSERT INTO resource_availability(resource_id,action,detail,created_at) VALUES(%ld,%s,%s,%s);\n", h.resourceId, q(h.action).c_str(), q(h.detail).c_str(), t(h.at).c_str());
    for (const auto& r : bundle.hospitals->findReservations())
        std::printf("INSERT INTO bed_reservations(id,hospital_id,incident_id,beds,reserved_from,reserved_until,released) VALUES(%ld,%ld,%ld,%d,%s,%s,%d);\n",
                    r.id, r.hospitalId, r.incidentId, r.beds, t(r.from).c_str(), t(r.until).c_str(), r.released ? 1 : 0);
    std::printf("\n");
    for (const auto& u : bundle.users->findAll())
        std::printf("INSERT INTO users(id,username,display_name,password_hash,salt,role_id,active,created_at) VALUES(%ld,%s,%s,%s,%s,(SELECT id FROM roles WHERE code=%s),%d,%s);\n",
                    u.id, q(u.username).c_str(), q(u.displayName).c_str(), q(u.passwordHash).c_str(), q(u.salt).c_str(), q(model::toString(u.role)).c_str(), u.active ? 1 : 0, t(u.createdAt).c_str());
    std::printf("\nCOMMIT;\nSET FOREIGN_KEY_CHECKS = 1;\n");
    return 0;
}
